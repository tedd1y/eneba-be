    /**
     * Seed every country and link it to its regions. Safe to run repeatedly.
     */
    public function run(): void
    {
        Country::query()->upsert(
            collect(self::COUNTRIES)
                ->map(fn (array $country, string $slug) => ['slug' => $slug, 'name' => $country[0], 'sort_order' => 0])
                ->values()
                ->all(),
            uniqueBy: ['slug'],
            update: ['name'],
        );

        $countryIds = Country::query()->pluck('id', 'slug');

        foreach (Region::query()->get() as $region) {
            $slugs = $region->slug === self::GLOBAL_REGION
                ? array_keys(self::COUNTRIES)
                : array_keys(array_filter(self::COUNTRIES, fn (array $country) => in_array($region->slug, $country[1], true)));

            $region->countries()->syncWithoutDetaching($countryIds->only($slugs)->values()->all());
        }
    }
